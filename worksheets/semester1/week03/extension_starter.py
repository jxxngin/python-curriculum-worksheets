# 3주 확장 프로젝트: 내가 태어난 요일 계산기
# 이 코드는 그대로 실행돼요. 날짜를 넣으면 무슨 요일인지 계산해요.
# '젤러의 공식'이라는 수학 공식을 썼어요. 공식은 바꾸지 말고, 바꾸기부터 시작해 보세요.

print("📅 내가 태어난 요일 계산기 📅")

year = int(input("태어난 해: "))
month = int(input("태어난 달: "))
day = int(input("태어난 날: "))

# 젤러의 공식에서는 1월, 2월을 '지난해의 13월, 14월'로 계산해요.
y = year
m = month
if m < 3:
    m = m + 12
    y = y - 1

k = y % 100     # 연도의 뒤 두 자리
j = y // 100    # 연도의 앞 두 자리
h = (day + (13 * (m + 1)) // 5 + k + k // 4 + j // 4 + 5 * j) % 7
# h가 0이면 토요일, 1이면 일요일, 2면 월요일 ... 6이면 금요일

print(f"계산 결과 h = {h}")

if h == 0:
    print("토요일에 태어났어요!")
elif h == 1:
    print("일요일에 태어났어요!")
else:
    print("평일에 태어났어요!")
