# 1주 미니 프로젝트: 생일 파티 초대장 (정답)
# 교안의 단계 순서대로 이어 쓴 완성본이에요.

# 단계 1: 제목 보여 주기
print("=================================")
print("        생일 파티 초대장")
print("=================================")

# 단계 2: 질문 4개 물어보기
host = input("생일인 사람의 이름은? ")
date = input("파티 날짜는? (예: 5월 3일) ")
place = input("파티 장소는? ")
guest = input("초대할 친구 이름은? ")

# 단계 3: 대답을 넣어 초대장 완성하기
# 초대장 내용
print("---------------------------------")
print(guest + "에게")
print(host + "의 생일 파티에 초대합니다!")
print("날짜: " + date + " / 장소: " + place)
print("꼭 와 줘! - " + host + " 드림")

