# ===== 1단계 따라 하기 완성본 =====
print("=================================")
print("     🎂 생일 파티 초대장 만들기 🎂")
print("=================================")

host = input("생일인 사람의 이름은? ")
date = input("파티 날짜는? (예: 5월 3일) ")
place = input("파티 장소는? ")
guest = input("초대할 친구 이름은? ")

print("")
print("---------------------------------")
print(guest + "에게")
print("")
print(host + "의 생일 파티에 초대합니다!")
print("날짜: " + date)
print("장소: " + place)
print("")
print("꼭 와 줘! - " + host + " 드림")
print("---------------------------------")

