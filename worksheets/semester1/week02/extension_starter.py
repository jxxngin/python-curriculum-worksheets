# 원리: 질문마다 고른 답("A" 또는 "B")을 이어 붙여서 "AB" 같은 성향 코드를 만들고,
#       코드가 무엇과 같은지(==) 비교해서 결과를 보여 줘요.

print("🎮 나의 게임 스타일 테스트 🎮")
print("")

print("Q1. 새 게임을 시작하면?")
print("A. 튜토리얼부터 꼼꼼히   B. 일단 달려 나간다")
q1 = input("> ").strip()

print("Q2. 보스가 너무 세다면?")
print("A. 레벨을 올리고 다시   B. 될 때까지 도전")
q2 = input("> ").strip()

code = q1 + q2
print("")
print("당신의 성향 코드: " + code)

if code == "AA":
    print("결과: 🛡️ 신중한 전략가")
elif code == "AB":
    print("결과: 📚 준비된 도전자")
elif code == "BA":
    print("결과: 🏃 자유로운 탐험가")
elif code == "BB":
    print("결과: 🔥 불굴의 돌격대장")
else:
    print("A 또는 B로만 답해 주세요. 대문자인지 확인!")
