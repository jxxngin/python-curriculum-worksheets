# 2학기 1주 도전 프로젝트: 국기 그리기 챌린지 (예시 답안)
# 일본 국기(시작 파일) + 스위스 국기 + 내가 고른 국기(프랑스)

import turtle

# 일본 국기 바탕: 가로 240, 세로 160인 흰 직사각형
turtle.penup()
turtle.goto(-260, -80)
turtle.pendown()
turtle.color("black", "white")
turtle.begin_fill()
turtle.goto(-20, -80)
turtle.goto(-20, 80)
turtle.goto(-260, 80)
turtle.goto(-260, -80)
turtle.end_fill()

# 가운데 빨간 원: 가운데 (-140, 0), 반지름 48
turtle.penup()
turtle.goto(-140, -48)
turtle.pendown()
turtle.color("red")
turtle.begin_fill()
turtle.circle(48)
turtle.end_fill()

# 스위스 국기는 여기부터: 바탕은 (40, -80)에서 (200, 80)까지인 빨간 정사각형
turtle.penup()
turtle.goto(40, -80)
turtle.pendown()
turtle.color("red")
turtle.begin_fill()
turtle.goto(200, -80)
turtle.goto(200, 80)
turtle.goto(40, 80)
turtle.goto(40, -80)
turtle.end_fill()

# 흰 십자가 가로 막대: (70, -15)에서 (170, 15)까지
turtle.penup()
turtle.goto(70, -15)
turtle.pendown()
turtle.color("white")
turtle.begin_fill()
turtle.goto(170, -15)
turtle.goto(170, 15)
turtle.goto(70, 15)
turtle.goto(70, -15)
turtle.end_fill()

# 흰 십자가 세로 막대: (105, -50)에서 (135, 50)까지
turtle.penup()
turtle.goto(105, -50)
turtle.pendown()
turtle.begin_fill()
turtle.goto(135, -50)
turtle.goto(135, 50)
turtle.goto(105, 50)
turtle.goto(105, -50)
turtle.end_fill()

# 내가 고른 국기: 프랑스(파랑·하양·빨강 세로 줄무늬), 아래 줄 (-260, -260)에서 (-20, -100)까지
turtle.penup()
turtle.goto(-260, -260)
turtle.pendown()
turtle.color("black", "blue")
turtle.begin_fill()
turtle.goto(-180, -260)
turtle.goto(-180, -100)
turtle.goto(-260, -100)
turtle.goto(-260, -260)
turtle.end_fill()
turtle.penup()
turtle.goto(-180, -260)
turtle.pendown()
turtle.color("black", "white")
turtle.begin_fill()
turtle.goto(-100, -260)
turtle.goto(-100, -100)
turtle.goto(-180, -100)
turtle.goto(-180, -260)
turtle.end_fill()
turtle.penup()
turtle.goto(-100, -260)
turtle.pendown()
turtle.color("black", "red")
turtle.begin_fill()
turtle.goto(-20, -260)
turtle.goto(-20, -100)
turtle.goto(-100, -100)
turtle.goto(-100, -260)
turtle.end_fill()

turtle.hideturtle()
# 이 줄은 늘 맨 아래에 둬요. 새 코드는 이 줄 위에 써요.
turtle.done()
