# 교사용: 꼭 하기 세 가지를 만족하는 바꾸기 예시
import turtle as t
t.color("teal")
t.pencolor("teal")
for side in range(3):
    t.forward(70)
    t.left(120)
# 단계 1 코드 아래에 이어서 써요.
t.left(90)
t.pencolor("orange")
for side in range(3):
    t.forward(70)
    t.left(120)
# 단계 2 코드 아래에 이어서 써요.
t.left(90)
t.pencolor("purple")
for side in range(3):
    t.forward(70)
    t.left(120)
# 단계 3 코드 아래에 이어서 써요.
t.left(90)
t.pencolor("red")
for side in range(3):
    t.forward(70)
    t.left(120)
t.done()
